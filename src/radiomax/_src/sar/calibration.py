"""Backscatter from a SAR image, normalised by three areas."""

from __future__ import annotations

from types import ModuleType
from typing import Any

from radiomax._src.backend import floating_inputs, like
from radiomax._src.labelled import elementwise
from radiomax._src.numerics import full_turn, to_radians


__all__ = [
    "beta0_to_sigma0",
    "dn_to_backscatter",
    "gamma0_to_sigma0",
    "sigma0_to_beta0",
    "sigma0_to_gamma0",
]


@elementwise()
def dn_to_backscatter(dn: Any, calibration: Any) -> Any:
    """Backscatter from a SAR image's digital numbers.

    x = (DN / A)²

    where x is β⁰, σ⁰ or γ⁰, according to the table A. Interpolating the table
    to the pixels, and subtracting the thermal noise, are the reader's.

    Args:
        dn: DN, the amplitude of the pixel: the digital number of a detected
            image, or |I + iQ| of a complex one.
        calibration: A, the product's calibration value for the quantity
            wanted, at each pixel.

    Returns:
        x, dimensionless and not in decibels; NaN where A is not positive.

    References:
        Miranda and Meadows (2015), *Radiometric Calibration of S-1 Level-1
        Products Generated by the S-1 IPF*, ESA-EOPG-CSCOP-TN-0002, issue 1.0,
        section 4.

    Examples:
        >>> from radiomax.sar import dn_to_backscatter
        >>> float(dn_to_backscatter(150.0, 300.0))
        0.25
    """
    xp, (dn, calibration) = floating_inputs(dn, calibration)
    valid = calibration > 0
    # the inner where keeps the unused branch finite, and so its gradient
    safe = xp.where(valid, calibration, xp.ones_like(calibration))
    # x = (DN / A)²
    backscatter = (dn / safe) ** 2
    return xp.where(valid, backscatter, like(xp.nan, backscatter, xp))


@elementwise()
def sigma0_to_beta0(sigma0: Any, incidence: Any, *, degrees: bool = True) -> Any:
    """Radar brightness β⁰ from the backscatter coefficient σ⁰.

    β⁰ = σ⁰ / sin θᵢ

    σ⁰ is per unit area of the ground, and β⁰ per unit area of the slant range
    plane.

    Args:
        sigma0: σ⁰, dimensionless and not in decibels.
        incidence: θᵢ, the angle of incidence, degrees (radians with
            ``degrees=False``).
        degrees: Whether the angle is in degrees.

    Returns:
        β⁰, dimensionless; NaN where the incidence is not in (0°, 90°).

    Examples:
        >>> from radiomax.sar import sigma0_to_beta0
        >>> round(float(sigma0_to_beta0(0.1, 30.0)), 12)
        0.2
    """
    xp, (sigma0, incidence) = floating_inputs(sigma0, incidence)
    sine, _ = _factors(incidence, xp, degrees=degrees)
    return sigma0 / sine


@elementwise()
def beta0_to_sigma0(beta0: Any, incidence: Any, *, degrees: bool = True) -> Any:
    """Backscatter coefficient σ⁰ from the radar brightness β⁰.

    σ⁰ = β⁰ sin θᵢ

    Args:
        beta0: β⁰, dimensionless and not in decibels.
        incidence: θᵢ, the angle of incidence, degrees (radians with
            ``degrees=False``).
        degrees: Whether the angle is in degrees.

    Returns:
        σ⁰, dimensionless; NaN where the incidence is not in (0°, 90°).

    Examples:
        >>> from radiomax.sar import beta0_to_sigma0
        >>> round(float(beta0_to_sigma0(0.2, 30.0)), 12)
        0.1
    """
    xp, (beta0, incidence) = floating_inputs(beta0, incidence)
    sine, _ = _factors(incidence, xp, degrees=degrees)
    return beta0 * sine


@elementwise()
def sigma0_to_gamma0(sigma0: Any, incidence: Any, *, degrees: bool = True) -> Any:
    """Backscatter γ⁰ from the backscatter coefficient σ⁰.

    γ⁰ = σ⁰ / cos θᵢ

    γ⁰ is per unit area of the plane perpendicular to the slant range. With
    the angle to the ellipsoid, it does not correct for terrain.

    Args:
        sigma0: σ⁰, dimensionless and not in decibels.
        incidence: θᵢ, the angle of incidence, degrees (radians with
            ``degrees=False``).
        degrees: Whether the angle is in degrees.

    Returns:
        γ⁰, dimensionless; NaN where the incidence is not in (0°, 90°).

    Examples:
        >>> from radiomax.sar import sigma0_to_gamma0
        >>> round(float(sigma0_to_gamma0(0.1, 60.0)), 12)
        0.2
    """
    xp, (sigma0, incidence) = floating_inputs(sigma0, incidence)
    _, cosine = _factors(incidence, xp, degrees=degrees)
    return sigma0 / cosine


@elementwise()
def gamma0_to_sigma0(gamma0: Any, incidence: Any, *, degrees: bool = True) -> Any:
    """Backscatter coefficient σ⁰ from γ⁰.

    σ⁰ = γ⁰ cos θᵢ

    Args:
        gamma0: γ⁰, dimensionless and not in decibels.
        incidence: θᵢ, the angle of incidence, degrees (radians with
            ``degrees=False``).
        degrees: Whether the angle is in degrees.

    Returns:
        σ⁰, dimensionless; NaN where the incidence is not in (0°, 90°).

    Examples:
        >>> from radiomax.sar import gamma0_to_sigma0
        >>> round(float(gamma0_to_sigma0(0.2, 60.0)), 12)
        0.1
    """
    xp, (gamma0, incidence) = floating_inputs(gamma0, incidence)
    _, cosine = _factors(incidence, xp, degrees=degrees)
    return gamma0 * cosine


def _factors(incidence: Any, xp: ModuleType, *, degrees: bool) -> tuple[Any, Any]:
    """sin θᵢ and cos θᵢ; NaN outside (0°, 90°), where one of them is not positive."""
    full = full_turn(degrees=degrees)
    valid = (incidence > 0) & (incidence < like(full / 4.0, incidence, xp))
    # the inner where keeps the unused branch finite, and so its gradient
    inside = xp.where(valid, incidence, like(full / 8.0, incidence, xp))
    angle = to_radians(inside, xp, degrees=degrees)
    nan = like(xp.nan, incidence, xp)
    return xp.where(valid, xp.sin(angle), nan), xp.where(valid, xp.cos(angle), nan)
